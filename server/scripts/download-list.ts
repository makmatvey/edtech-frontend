/**
 * Генерирует чек-лист «что скачать и куда положить» по каталогу учебников.
 * Запуск: npm run download-list  →  materials/СПИСОК ДЛЯ СКАЧИВАНИЯ.txt
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CATALOG, LIBRARY_SUBJECTS } from "../src/data/library.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, "../../materials/СПИСОК ДЛЯ СКАЧИВАНИЯ.txt");
const BS = "\\";
const dir = (...parts: string[]) => ["materials", ...parts].join(BS) + BS;

const L: string[] = [];
const p = (s = "") => L.push(s);
const bar = (t: string) => { p(); p("=".repeat(78)); p(t); p("=".repeat(78)); };
const ORDER = [7, 5, 9, 6, 8, 10, 11];
const word = (n: number) => (n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? "учебника" : n % 10 === 1 && n % 100 !== 11 ? "учебник" : "учебников");

p("КЛАСНА — ЧТО СКАЧАТЬ И КУДА ПОЛОЖИТЬ");
p(`Учебников в каталоге: ${CATALOG.length} (5–11 классы, ${LIBRARY_SUBJECTS.length} предметов).`);
p();
p(`Все пути — внутри папки проекта: Рабочий стол${BS}Klasna${BS}materials${BS}`);
p("Папки уже созданы. Положил файл — через несколько секунд он на сайте, перезапуск не нужен.");
p("Отмечайте сделанное: [ ] → [x]");
p();
p("ВАЖНО: сайты *.adu.by (e-padruchnik, profil, lingvo) открываются только из белорусской сети.");
p("Если не открываются — выключите VPN или скачивайте с телефона через мобильный интернет / со школьного ПК.");
p("eior.by (видео) может попросить вход — учётную запись учителя выдаёт школа.");
p();
p("ПОРЯДОК (сначала то, что нужно для показа, отмечено ★):");
p("  1) ОБЛОЖКИ учебников 5–11 классов — по ним учебник узнают на полке (раздел 1)");
p("  2) PDF учебников — НЕ обязательно: на показе достаточно сказать, что их можно подключить");
p("  3) Видео ЕИОР, методички profil.adu.by, аудио Lingvo");

bar("1. ОБЛОЖКИ УЧЕБНИКОВ — e-padruchnik.adu.by");
p("Где: https://e-padruchnik.adu.by — каталог учебных пособий с обложками.");
p("Брать издание на 2026/2027 учебный год, на русском языке (белорусский язык и литература — на белорусском).");
p();
p("БЫСТРЫЙ СПОСОБ (обложки разложатся сами):");
p("  1. Откройте в Chrome страницу каталога с обложками (например, все учебники одного класса).");
p(`  2. Ctrl+S → тип «Веб-страница полностью» → сохраните в одну папку, например Загрузки${BS}обложки.`);
p("  3. Повторите для каждого класса 5–11 (в ту же папку).");
p(`  4. Выполните в папке проекта:  npm run import-covers -w server -- "%USERPROFILE%${BS}Downloads${BS}обложки"`);
p(`     (или просто напишите Claude «обложки в Загрузках${BS}обложки» — разложит сам).`);
p();
p("РУЧНОЙ СПОСОБ: правой кнопкой по обложке → «Сохранить картинку как…» → имя «Алгебра 7.jpg»");
p("  прямо в папку учебника ниже, либо всё в одну папку и тот же import-covers.");
p();
p("PDF (по желанию): кнопка скачивания PDF у пособия → в ту же папку учебника.");
p("Если учебник из нескольких частей — все PDF в ту же папку: «Часть 1.pdf», «Часть 2.pdf».");
for (const g of ORDER) {
  const list = CATALOG.filter((b) => b.grade === g);
  p();
  p(`--- ${g} класс: ${list.length} ${word(list.length)}${g === 7 ? " — СНАЧАЛА ЭТОТ" : ""}`);
  for (const b of list) {
    const star = g === 7 && (b.subject_code === "algebra" || b.subject_code === "geometry") ? " ★" : "";
    p(`[ ] обложка  [ ] PDF   ${b.title}${b.authors ? ` (${b.authors})` : ""}${star}`);
    p(`      → ${dir("Учебники", b.subject, String(g))}`);
  }
}

bar("2. ВИДЕОУРОКИ — eior.by");
p("Где: https://eior.by → разделы «Демонстрационные материалы» и «База знаний».");
p("Подходят только видеофайлы .mp4 (анимации, которые работают только в браузере, не сохраняются).");
p(`Куда: ${dir("ЕИОР — Видеоуроки", "<Предмет>", "<класс>")}`);
p("Имя файла = название на сайте; номер в начале задаёт порядок: «01_Одночлены.mp4».");
p();
p(`[ ] Алгебра 7 — 3–5 роликов (одночлены, многочлены, степени) ★   → ${dir("ЕИОР — Видеоуроки", "Алгебра", "7")}`);
p(`[ ] Геометрия 7 — 2–3 ролика (треугольники, признаки равенства)  → ${dir("ЕИОР — Видеоуроки", "Геометрия", "7")}`);
p("[ ] Физика 7 и 9, Биология 7 и 9, История Беларуси 7 и 9 — по 1–3 ролика");
p("[ ] Остальные предметы и классы — по мере возможности");

bar("3. МЕТОДИКА — profil.adu.by");
p("Где: https://profil.adu.by → страница предмета.");
p();
p("3.1. Инструктивно-методическое письмо на 2026/2027 учебный год — по каждому предмету:");
for (const s of LIBRARY_SUBJECTS) p(`[ ] ${s.name.padEnd(24)} → ${dir("Методика (profil.adu.by)", "Советы по предметам", s.name)}`);
p();
p(`3.2. Как создавать интерактивные задания (PDF)  → ${dir("Методика (profil.adu.by)", "Интерактивные задания")}`);
p("[ ] найдено и скачано");
p(`3.3. Как создавать электронные курсы (PDF)      → ${dir("Методика (profil.adu.by)", "Электронные курсы")}`);
p("[ ] найдено и скачано");
p(`3.4. Рекомендации по сложным и новым темам      → ${dir("Методика (profil.adu.by)", "Особые темы")}`);
p("[ ] найдено и скачано");

bar("4. АУДИО ДЛЯ ЯЗЫКОВ — lingvo.adu.by");
p("Что: аудиоприложения к учебникам английского языка (диалоги, тексты для аудирования), .mp3");
p(`Куда: ${dir("Лингва — Аудио", "Английский язык", "<класс>")}  (можно подпапки по урокам: «Unit 3»)`);
p();
for (const g of ORDER) p(`[ ] Английский язык, ${g} класс${g === 7 ? " ★" : ""}   → ${dir("Лингва — Аудио", "Английский язык", String(g))}`);
p();
p("Если есть аудио по русскому или белорусскому языку — в папки «Русский язык» / «Беларуская мова».");

bar("5. ЧТО НЕ СКАЧИВАЕТСЯ");
p("Тесты, тренажёры и творческие задания ЕИОР работают только в браузере.");
p("Самые нужные из них можно пересобрать в «Конструкторе заданий» (меню учителя → Материалы).");
p();
p("Перед публичным показом сайта проверьте условия использования скачанных материалов.");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, "﻿" + L.join("\r\n") + "\r\n", "utf8");
console.log(`Готово: ${OUT} (${CATALOG.length} учебников)`);
