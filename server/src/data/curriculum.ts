export type ExpandedTopic = {
  seq: number;
  sectionNo: number;
  section: string;
  title: string;
  paragraph: string | null;
  kind: "regular" | "control" | "review";
};

/** Строчная первая буква, кроме аббревиатур (ВКЛ, СПП). */
const lowerFirst = (t: string) => (t.length > 1 && t[1] === t[1].toUpperCase() && /\p{L}/u.test(t[1]) ? t : t[0].toLowerCase() + t.slice(1));

const SOLVING = new Set(["math", "algebra", "geometry", "physics"]);
const FILLER: Record<string, (t: string) => string> = {
  english: (t) => `Practice: ${t}`,
  belarusian: (t) => `Замацаванне: ${lowerFirst(t)}`,
  solving: (t) => `Решение задач: ${lowerFirst(t)}`,
  default: (t) => `Закрепление: ${lowerFirst(t)}`,
};
const CONTROL: Record<string, (t: string) => string> = {
  english: (t) => `Test: ${t}`,
  belarusian: (t) => `Кантрольная работа: ${lowerFirst(t)}`,
  default: (t) => `Контрольная работа: ${lowerFirst(t)}`,
};

/** Разворачивает разделы в последовательность уроков (тема на каждый урок). */
export function expand(c: Curriculum): ExpandedTopic[] {
  const out: ExpandedTopic[] = [];
  let paragraph = 0;
  c.sections.forEach((s, si) => {
    const filler = FILLER[c.subject] ?? (SOLVING.has(c.subject) ? FILLER.solving : FILLER.default);
    const control = CONTROL[c.subject] ?? CONTROL.default;
    const regularCount = s.control ? s.hours - 1 : s.hours;
    // Распределяем часы по пунктам: первый урок — новая тема, следующие — закрепление.
    const n = Math.min(s.items.length, regularCount);
    const plan: { item: number; first: boolean }[] = [];
    for (let k = 0; k < n; k++) {
      const share = Math.floor(regularCount / n) + (k < regularCount % n ? 1 : 0);
      for (let j = 0; j < share; j++) plan.push({ item: k, first: j === 0 });
    }
    for (let i = 0; i < s.hours; i++) {
      let title: string;
      let kind: ExpandedTopic["kind"] = "regular";
      if (s.control && i === s.hours - 1) {
        title = control(s.title);
        kind = "control";
      } else if (plan[i]?.first) {
        title = s.items[plan[i].item];
        paragraph++;
      } else {
        title = filler(s.items[plan[i]?.item ?? 0] ?? s.title);
        kind = "review";
      }
      out.push({
        seq: out.length + 1,
        sectionNo: si + 1,
        section: s.title,
        title,
        paragraph: c.grade === 6 || c.grade === 8 ? null : c.subject === "english" ? `Unit ${si + 1}` : `§ ${Math.max(paragraph, 1)}`,
        kind,
      });
    }
  });
  return out;
}
